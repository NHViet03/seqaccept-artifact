"""Shortlist IDoFT Python repos (week 1) and screen them by running them (plan days 5-7).
Usage: uv run python screen_idoft.py [py-data.csv]   (run_all.py screens every shortlisted repo overnight)

Keeps order-dependent (OD*) and random (NOD) flaky tests in repos that are not archived/deleted/unmaintained.
NIO tests (fail only when run twice in the same process) are dropped: every block uses a fresh container.
Repos having both kinds of flakiness come first. `screen` builds a repo at its IDoFT commit and runs its flaky tests'
files: does it install, do the tests run offline, does the flake reproduce (random vs default order, Prop. 10),
what is the background rate p0 once the IDoFT tests are deselected (plan 2.3), how long is a block.
"""
import csv
import io
import re
import subprocess
import sys
import urllib.request
from pathlib import Path
from statistics import mean

from collect import MAX_BLOCK_SECONDS, make_run, now, pool_map
from run_block import BlockError

URL = "https://raw.githubusercontent.com/TestingResearchIllinois/idoft/main/py-data.csv"
KEEP = ("OD", "OD-Vic", "OD-Brit", "NOD")
DEAD = {"Unmaintained", "RepoArchived", "RepoDeleted", "Deleted"}
SCREEN_BLOCKS = 20  # random-order blocks with and without the IDoFT tests
SUMMARY = ("slug", "verdict", "kinds", "idoft_tests", "flaky_rate", "default_order_failed", "p0_estimate",
           "seconds_per_block", "missing_modules", "url", "sha", "detail")


def shortlist(text):
    repos = {}  # (url, sha) -> {"tests": [...], "cats": set}
    for r in csv.DictReader(io.StringIO(text)):
        cat, status = r["Category"].strip(), r["Status"].strip()
        if cat not in KEEP or status in DEAD:
            continue
        entry = repos.setdefault((r["Project URL"], r["SHA Detected"]), {"tests": [], "cats": set()})
        entry["tests"].append(r["Pytest Test Name (PathToFile::TestClass::TestMethod or PathToFile::TestMethod)"])
        entry["cats"].add("NOD" if cat == "NOD" else "OD")
    rows = [{"url": u, "sha": s, "tests": e["tests"], "kinds": sorted(e["cats"])} for (u, s), e in repos.items()]
    rows.sort(key=lambda r: (-len(r["kinds"]), -len(r["tests"])))  # stable: ties keep CSV order
    return rows


def slug(row):
    owner_repo = row["url"].rstrip("/").split("github.com/")[-1]
    return re.sub(r"[^a-z0-9]+", "_", f"{owner_repo}_{row['sha'].strip()[:8]}".lower()).strip("_")


def dockerfile(row):
    """Same recipe as repos/<name>/Dockerfile. Install steps never fail the build: a repo whose tests cannot import
    is caught when they run, with the reason."""
    return (f"# {row['url']} at IDoFT commit {row['sha'].strip()} (generated by screen_idoft.py)\n"
            "FROM seqaccept/base:1\n"
            f"RUN git clone -q {row['url'].rstrip('/')} /repo && git -C /repo checkout -q {row['sha'].strip()}\n"
            "WORKDIR /repo\n"
            "RUN pip install --no-cache-dir -e . || true\n"
            "RUN for f in $(ls *requirements*.txt requirements/*.txt 2>/dev/null); do "
            "pip install --no-cache-dir -r $f || true; done\n")


def screen(row, runner=subprocess.run, workers=2, n=SCREEN_BLOCKS, root="repos/idoft"):
    """Build and run one IDoFT repo/commit. Returns the screening record; "verdict" is "candidate" when it installs,
    its tests run offline, the flake reproduces, p0 <= 0.05 without the IDoFT tests and a block takes <= 15 s.
    The image is removed unless it is a candidate."""
    name = slug(row)
    image, folder = f"seqaccept-screen/{name}:1", Path(root) / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "Dockerfile").write_text(dockerfile(row))
    out = {"slug": name, "url": row["url"], "sha": row["sha"].strip(), "kinds": "+".join(row["kinds"]),
           "idoft_tests": len(row["tests"]), "tests": row["tests"], "image": image, "screened_at": now()}
    try:
        runner(["docker", "build", "-q", "-t", image, str(folder)], capture_output=True, text=True, timeout=1800,
               check=True)
    except subprocess.CalledProcessError as e:
        return {**out, "verdict": "build failed", "detail": ((e.stderr or "") + (e.stdout or ""))[-600:]}
    except subprocess.TimeoutExpired:
        return {**out, "verdict": "build timed out"}
    files = sorted({t.split("::")[0] for t in row["tests"]})
    flaky = {"image": image, "relpath": None, "tests": files}
    clean = {**flaky, "tests": files + [f"--deselect={t}" for t in row["tests"]]}
    pmap = pool_map(workers)
    try:
        res = list(pmap(lambda seed: make_run(flaky, runner=runner)("", seed), range(1, n + 1)))
        default = make_run(flaky, default_order=True, runner=runner)("", 1)
    except BlockError as e:
        out.update(verdict="tests do not run", detail=str(e)[-600:])
    else:
        failed_ids = sorted({m for r in res for m in re.findall(r"FAILED (\S+)", r.output)})
        out.update(flaky_rate=mean(r.failed for r in res), default_order_failed=default.failed,
                   seconds_per_block=mean(r.seconds for r in res), failing_tests=failed_ids,
                   missing_modules=sorted({m for r in res for m in re.findall(r"No module named '([^']+)'", r.output)}))
        try:
            out["p0_estimate"] = mean(r.failed for r in pmap(lambda seed: make_run(clean, runner=runner)("", seed),
                                                                range(1, n + 1)))
        except BlockError:
            out["p0_estimate"] = None  # nothing left once the IDoFT tests are deselected
        out["verdict"] = (
            "tests need uninstalled modules" if out["missing_modules"] and out["flaky_rate"] == 1 else
            "flake not reproduced" if out["flaky_rate"] == 0 else
            "no tests left without the flaky ones" if out["p0_estimate"] is None else
            "p0 > 0.05 without the flaky tests" if out["p0_estimate"] > 0.05 else
            "block too slow" if out["seconds_per_block"] > MAX_BLOCK_SECONDS else "candidate")
    if out["verdict"] != "candidate":
        runner(["docker", "rmi", "-f", image], capture_output=True, text=True)
    return out


def write_summary(records, path):
    """screening/summary.csv: one row per repo/commit (the plan's screening log, the paper's selection-filter threat)."""
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, SUMMARY, extrasaction="ignore")
        w.writeheader()
        for r in sorted(records, key=lambda r: (r["verdict"] != "candidate", r["slug"])):
            w.writerow({**r, "missing_modules": " ".join(r.get("missing_modules", []))})


if __name__ == "__main__":
    text = open(sys.argv[1]).read() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()
    rows = shortlist(text)
    print(f"{len(rows)} repo/commit pairs; top 30:")
    for r in rows[:30]:
        print(f"{'+'.join(r['kinds']):6} {len(r['tests']):4} tests  {r['url']}  {r['sha'][:10]}")
